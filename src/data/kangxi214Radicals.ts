export function getKangxiRadicalByNumber(num: number): KangxiRadicalFullEntry | undefined {
  return KANGXI_214_RADICALS.find((r) => r.number === num);
}

export function searchKangxi214Radicals(query: string): KangxiRadicalFullEntry[] {
  if (!query || !query.trim()) return KANGXI_214_RADICALS;
  const q = query.trim().toLowerCase();
  return KANGXI_214_RADICALS.filter(
    (r) =>
      r.name.toLowerCase().includes(q) ||
      r.reading.toLowerCase().includes(q) ||
      r.char === q ||
      r.displayChar === q ||
      (r.altChars && r.altChars.some((c) => c === q)) ||
      r.kanjiList.some((k) => k === q) ||
      r.description.toLowerCase().includes(q)
  );
}
